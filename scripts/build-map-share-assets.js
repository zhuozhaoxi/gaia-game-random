#!/usr/bin/env node

'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {execFileSync} = require('node:child_process');

const root = path.resolve(__dirname, '..');
const sourceDirectory = path.join(root, 'doc/gaia/map');
const outputFile = path.join(root, 'js/map-share-assets.js');
const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), 'gaia-map-share-'));

function targetWidth(filename) {
    if (/^(0[1-9]|10)-实心\.png$/.test(filename)) return 300;
    if (/^1[1-8]-(实心|空心)\.png$/.test(filename)) return 160;
    return 80;
}

try {
    const assets = {};
    const filenames = fs.readdirSync(sourceDirectory)
        .filter(filename => filename.endsWith('.png'))
        .sort((first, second) => first.localeCompare(second, 'zh-CN'));

    for (const filename of filenames) {
        const source = path.join(sourceDirectory, filename);
        const resized = path.join(temporaryDirectory, filename);
        fs.copyFileSync(source, resized);
        execFileSync('/usr/bin/sips', ['--resampleWidth', String(targetWidth(filename)), resized], {stdio: 'ignore'});
        assets[filename] = `data:image/png;base64,${fs.readFileSync(resized).toString('base64')}`;
    }

    const output = `// Generated by scripts/build-map-share-assets.js.\nwindow.GAIA_MAP_SHARE_ASSETS=${JSON.stringify(assets)};\n`;
    fs.writeFileSync(outputFile, output);
    console.log(`Wrote ${filenames.length} embedded map assets to ${outputFile}`);
} finally {
    fs.rmSync(temporaryDirectory, {recursive: true, force: true});
}
