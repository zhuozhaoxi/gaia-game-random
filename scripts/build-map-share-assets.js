#!/usr/bin/env node

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourceDirectory = path.join(root, 'doc/gaia/map');
const outputFile = path.join(root, 'js/map-share-assets.js');

const assets = {};
const filenames = fs.readdirSync(sourceDirectory)
    .filter(filename => filename.endsWith('.png'))
    .sort((first, second) => first.localeCompare(second, 'zh-CN'));

for (const filename of filenames) {
    const source = path.join(sourceDirectory, filename);
    assets[filename] = `data:image/png;base64,${fs.readFileSync(source).toString('base64')}`;
}

const output = `// Generated by scripts/build-map-share-assets.js.\nwindow.GAIA_MAP_SHARE_ASSETS=${JSON.stringify(assets)};\n`;
fs.writeFileSync(outputFile, output);
console.log(`Wrote ${filenames.length} embedded map assets to ${outputFile}`);
